#!/bin/bash

# Переходим в корень проекта
cd "$(dirname "$0")"

# Создаем папку для логов, чтобы можно было проверить результаты позже
mkdir -p logs

echo "Начинаю процесс авторизации для всех аккаунтов..."
echo "Список аккаунтов будет взят из папки cookies/"

# Получаем список всех файлов .json в папке cookies
# Используем basename, чтобы убрать путь, и sed, чтобы убрать .json
accounts=$(ls cookies/*.json | xargs -n 1 basename | sed 's/\.json$//')

count=0
total=$(echo "$accounts" | wc -l)

for account in $accounts; do
    count=$((count + 1))
    echo "----------------------------------------------------------------"
    echo "[$count/$total] Обработка аккаунта: $account"
    echo "----------------------------------------------------------------"
    
    # Запуск скрипта и запись вывода в лог-файл для каждого аккаунта
    npm start "$account" 2>&1 | tee "logs/${account}.log"
    
    echo "Завершено для $account. Перехожу к следующему..."
    echo ""
done

echo "================================================================"
echo "Все аккаунты обработаны. Логи доступны в папке logs/"
echo "================================================================"
